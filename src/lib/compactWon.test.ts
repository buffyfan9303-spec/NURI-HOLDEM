import { describe, it, expect } from 'vitest';
import { compactWon } from './compactWon';

describe('compactWon — 캘린더 칸·요약의 짧은 금액(버림, 부풀리지 않는다)', () => {
  it.each([
    [969_567, '+96.9만'], [1_234_567, '+123만'], [-1_500_000, '-150만'], [45_000, '+4.5만'],
    [5_000, '+5,000'], [-9_999, '-9,999'], [0, '0'], [10_000, '+1만'], [99_990_000, '+9999만'],
    [123_456_789, '+1.2억'], [1_987_654_321, '+19억'], [-15_990, '-1.5만'],
  ])('%d → %s', (n, s) => { expect(compactWon(n)).toBe(s); });
});
