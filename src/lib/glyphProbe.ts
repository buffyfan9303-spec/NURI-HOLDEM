// 그 **예외 목록**을 한 파일에 담고 있었다. 2026-09-18 오너 지시로 규약 자체는 삭제됐는데
// (`ca891a4` — "이모지는 사용하지말라는 규칙 삭제 너가 생각하기에 꼭 필요한 곳은 사용"),
